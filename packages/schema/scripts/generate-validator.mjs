import { mkdir, readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { Ajv2020 } from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const schemaUrl = new URL("../graph.schema.json", import.meta.url);
const outputUrl = new URL("../src/generated/graph-validator.ts", import.meta.url);

function browserSafeStandalone(code) {
  const imports = [];
  let transformed = code;

  transformed = transformed.replace(
    /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
    (_match, name) => {
      imports.push(
        [
          'import ucs2LengthModule from "ajv/dist/runtime/ucs2length.js";',
          'const ucs2Length = typeof ucs2LengthModule === "function" ? ucs2LengthModule : ucs2LengthModule.default;',
        ].join("\n"),
      );
      return `const ${name} = ucs2Length;`;
    },
  );
  transformed = transformed.replace(
    /const (\w+) = require\("ajv\/dist\/runtime\/equal"\)\.default;/g,
    (_match, name) => {
      imports.push(
        [
          'import equalModule from "ajv/dist/runtime/equal.js";',
          'const equal = typeof equalModule === "function" ? equalModule : equalModule.default;',
        ].join("\n"),
      );
      return `const ${name} = equal;`;
    },
  );
  transformed = transformed.replace(
    /const (\w+) = require\("ajv-formats\/dist\/formats"\)\.fullFormats\["date-time"\];/g,
    (_match, name) => {
      imports.push(
        'import formatDefinitions from "ajv-formats/dist/formats.js";',
      );
      return `const ${name} = formatDefinitions.fullFormats["date-time"];`;
    },
  );

  for (const forbidden of ["require(", "new Function", "node:", "process."]) {
    if (transformed.includes(forbidden)) {
      throw new Error(
        `Generated browser validator contains forbidden runtime token "${forbidden}".`,
      );
    }
  }

  return `${[
    "// Generated by scripts/generate-validator.mjs. Do not edit.",
    "// @ts-nocheck",
    ...[...new Set(imports)].sort(),
    transformed,
  ].join("\n").trimEnd()}\n`;
}

const schema = JSON.parse(await readFile(schemaUrl, "utf8"));
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: {
    esm: true,
    lines: true,
    source: true,
  },
});
addFormats(ajv);
const generated = browserSafeStandalone(
  standaloneCode(ajv, ajv.compile(schema)),
);

if (process.argv.includes("--check")) {
  const current = await readFile(outputUrl, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error(
      `${fileURLToPath(outputUrl)} is stale. Run "yarn schema:generate".`,
    );
  }
} else {
  await mkdir(new URL("../src/generated/", import.meta.url), {
    recursive: true,
  });
  await writeFile(outputUrl, generated);
}
